-- NAMING CONVENTIONS
-- ------------------
-- Database and table names use uppercase singular nouns with underscores.
-- Attribute names use an entity specific prefix, such as CUST_ for CUSTOMER
-- and VEH_ for VEHICLE, keeping column names clear in multi table joins.
-- Primary key constraints use PK_TABLENAME, foreign keys use
-- FK_CHILDTABLE_PARENTTABLE, unique constraints use UK_TABLENAME_COLUMN,
-- and check constraints use CK_TABLENAME_COLUMN. Surrogate integer keys
-- identify the main entities, while VEHICLE uses VIN as its natural primary
-- key and the financing subtypes inherit ACCOUNT_ID from FINANCING_ACCOUNT.

-- SQL CREATE statements
-- ---------------------
-- Create and select the database
DROP DATABASE IF EXISTS BHPH_DEALERSHIP;
CREATE DATABASE BHPH_DEALERSHIP;
USE BHPH_DEALERSHIP;

-- CUSTOMER
CREATE TABLE CUSTOMER (
    CUSTOMER_ID       INT             NOT NULL,
    CUST_FIRST_NAME   VARCHAR(35)     NOT NULL,
    CUST_LAST_NAME    VARCHAR(35)     NOT NULL,
    CUST_DOB          DATE            NOT NULL,
    CUST_DL_NUMBER    VARCHAR(20)     NOT NULL,
    CUST_PHONE        VARCHAR(15)     NOT NULL,
    CUST_EMAIL        VARCHAR(60),
    CUST_ADDRESS      VARCHAR(80)     NOT NULL,
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID)
);

-- VEHICLE
CREATE TABLE VEHICLE (
    VIN                     CHAR(17)        NOT NULL,
    VEH_YEAR                SMALLINT        NOT NULL,
    VEH_MAKE                VARCHAR(25)     NOT NULL,
    VEH_MODEL               VARCHAR(25)     NOT NULL,
    VEH_MILEAGE             INT             NOT NULL,
    VEH_ACQUISITION_COST    DECIMAL(10,2)   NOT NULL,
    VEH_LIST_PRICE          DECIMAL(10,2)   NOT NULL,
    VEH_STATUS              VARCHAR(20)     NOT NULL,
    CONSTRAINT PK_VEHICLE PRIMARY KEY (VIN)
);

-- SALE
CREATE TABLE SALE (
    SALE_ID                 INT             NOT NULL,
    CUSTOMER_ID             INT             NOT NULL,
    VIN                     CHAR(17)        NOT NULL,
    SALE_DATE               DATE            NOT NULL,
    SALE_PRICE              DECIMAL(10,2)   NOT NULL,
    SALE_DOWN_PAYMENT       DECIMAL(10,2)   NOT NULL,
    SALE_TRADE_IN_ALLOWANCE DECIMAL(10,2)   NOT NULL,
    SALE_TAX_AMOUNT         DECIMAL(10,2)   NOT NULL,
    CONSTRAINT PK_SALE PRIMARY KEY (SALE_ID),
    CONSTRAINT FK_SALE_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID),
    CONSTRAINT FK_SALE_VEHICLE FOREIGN KEY (VIN)
        REFERENCES VEHICLE (VIN)
);

-- FINANCING_ACCOUNT (supertype)
CREATE TABLE FINANCING_ACCOUNT (
    ACCOUNT_ID              INT             NOT NULL,
    SALE_ID                 INT             NOT NULL,
    ACCT_ORIGINATION_DATE   DATE            NOT NULL,
    ACCT_AMOUNT_FINANCED    DECIMAL(10,2)   NOT NULL,
    ACCT_APR                DECIMAL(5,2)    NOT NULL,
    ACCT_TERM_MONTHS        SMALLINT        NOT NULL,
    ACCT_TOTAL_OF_PAYMENTS  DECIMAL(10,2)   NOT NULL,
    ACCT_TYPE               CHAR(1)         NOT NULL,
    CONSTRAINT PK_FINANCING_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UK_FINANCING_ACCOUNT_SALE_ID UNIQUE (SALE_ID),
    CONSTRAINT FK_FINANCING_ACCOUNT_SALE FOREIGN KEY (SALE_ID)
        REFERENCES SALE (SALE_ID),
    CONSTRAINT CK_FINANCING_ACCOUNT_ACCT_TYPE CHECK (ACCT_TYPE IN ('I','E'))
);

-- INHOUSE_ACCOUNT (subtype)
CREATE TABLE INHOUSE_ACCOUNT (
    ACCOUNT_ID              INT             NOT NULL,
    INH_PAYMENT_FREQUENCY   VARCHAR(10)     NOT NULL,
    INH_PAYMENT_AMOUNT      DECIMAL(8,2)    NOT NULL,
    INH_FIRST_DUE_DATE      DATE            NOT NULL,
    INH_NEXT_DUE_DATE       DATE            NOT NULL,
    INH_CURRENT_BALANCE     DECIMAL(10,2)   NOT NULL,
    INH_DELINQUENCY_STATUS  VARCHAR(15)     NOT NULL,
    INH_DAYS_PAST_DUE       SMALLINT        NOT NULL,
    CONSTRAINT PK_INHOUSE_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT FK_INHOUSE_ACCOUNT_FINANCING_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES FINANCING_ACCOUNT (ACCOUNT_ID)
);

-- EXTERNAL_LENDER
CREATE TABLE EXTERNAL_LENDER (
    LENDER_ID                   INT             NOT NULL,
    LENDER_NAME                 VARCHAR(50)     NOT NULL,
    LENDER_CONTACT_NAME         VARCHAR(50)     NOT NULL,
    LENDER_PHONE                VARCHAR(15)     NOT NULL,
    LENDER_EMAIL                VARCHAR(60),
    LENDER_REMITTANCE_ADDRESS   VARCHAR(80)     NOT NULL,
    LENDER_DEALER_ACCOUNT_NUM   VARCHAR(20)     NOT NULL,
    LENDER_APPROVAL_TIER        VARCHAR(10)     NOT NULL,
    CONSTRAINT PK_EXTERNAL_LENDER PRIMARY KEY (LENDER_ID)
);

-- EXTERNAL_ACCOUNT (subtype)
CREATE TABLE EXTERNAL_ACCOUNT (
    ACCOUNT_ID                  INT             NOT NULL,
    LENDER_ID                   INT             NOT NULL,
    EXT_APPLICATION_DATE        DATE            NOT NULL,
    EXT_APPROVAL_DATE           DATE,
    EXT_FUNDING_DATE            DATE,
    EXT_APPROVAL_STATUS         VARCHAR(15)     NOT NULL,
    EXT_CONTRACT_PURCHASE_AMT   DECIMAL(10,2)   NOT NULL,
    EXT_DEALER_RESERVE_AMT      DECIMAL(8,2)    NOT NULL,
    CONSTRAINT PK_EXTERNAL_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT FK_EXTERNAL_ACCOUNT_FINANCING_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES FINANCING_ACCOUNT (ACCOUNT_ID),
    CONSTRAINT FK_EXTERNAL_ACCOUNT_EXTERNAL_LENDER FOREIGN KEY (LENDER_ID)
        REFERENCES EXTERNAL_LENDER (LENDER_ID)
);

-- PAYMENT
CREATE TABLE PAYMENT (
    PAYMENT_ID                  INT             NOT NULL,
    ACCOUNT_ID                  INT             NOT NULL,
    PMT_DATE                    DATE            NOT NULL,
    PMT_AMOUNT                  DECIMAL(8,2)    NOT NULL,
    PMT_METHOD                  VARCHAR(15)     NOT NULL,
    PMT_RECEIPT_NUMBER          VARCHAR(20)     NOT NULL,
    PMT_APPLIED_TO_PRINCIPAL    DECIMAL(8,2)    NOT NULL,
    PMT_APPLIED_TO_INTEREST     DECIMAL(8,2)    NOT NULL,
    CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAYMENT_INHOUSE_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES INHOUSE_ACCOUNT (ACCOUNT_ID)
);

